"""Write the step list of the m3resp step registry to src/js/data/step-info.js.

The GUI mockup reads this file to fill the Operations palette and the help
box: the name, one-line summary, modality, category, inputs, outputs and
parameters of every registered step.

Run it from the repository root, in the environment where m3resp is installed:

    .venv/bin/python tools/mockup_tool/export_step_info.py
"""

import json
import os

from m3resp.workflows.registry import describe_steps

OUTPUT_PATH = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "src", "js", "data", "step-info.js"
)


def _ports(artifacts):
    """Return [name, artifact type] for every input or output of a step."""
    return [[a.name, a.artifact_type] for a in artifacts if not a.compatibility_only]


def _parameter(p):
    """Return one parameter with only the fields the mockup shows."""
    return {
        "name": p.name,
        "type": p.value_type,
        "default": p.default,
        "unit": p.unit,
        "min": p.minimum,
        "max": p.maximum,
        "choices": list(p.choices) if p.choices is not None else None,
        "desc": p.description,
        "advanced": p.advanced,
    }


def build_step_info():
    """Return {step name: info} for every step in the registry."""
    info = {}
    for step in sorted(describe_steps(), key=lambda s: s.name):
        info[step.name] = {
            "summary": step.summary,
            "modality": step.modality or "generic",
            "category": step.category or "other",
            "ins": _ports(step.input_artifacts),
            "outs": _ports(step.output_artifacts),
            "params": [_parameter(p) for p in step.parameters],
            "packages": list(step.optional_packages),
        }
    return info


def main():
    info = build_step_info()
    text = (
        "// Generated by tools/mockup_tool/export_step_info.py from\n"
        "// m3resp.workflows.registry.describe_steps(). Run that script again\n"
        "// after a change to the step registry; do not edit this file by hand.\n"
        f"const STEP_INFO = {json.dumps(info, ensure_ascii=False)};\n"
    )
    with open(OUTPUT_PATH, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"Wrote {len(info)} steps to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
